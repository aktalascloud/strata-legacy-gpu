const draft = { kind: 'provider', provider: 'freellm', models: [] };
const row = (id, context = 1000) => ({ id, name: id, isFree: true, pricing: { prompt: '0', completion: '0' }, context_length: context, top_provider: { max_completion_tokens: 120 }, architecture: { input_modalities: ['text'] }, supported_parameters: ['reasoning'] });
const listen = server => new Promise(resolve => server.listen(0, '127.0.0.1', () => resolve(`http://127.0.0.1:${server.address().port}`)));
const close = server => new Promise(resolve => server.close(resolve));

test('FreeLLM discovers only eligible free models and refreshes live limits without a key', async t => {
  const directory = mkdtempSync(join(tmpdir(), 'strata-freellm-'));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  let context = 1000, available = true, status = 200;
  const calls = [];
  const service = createModelProviders({ directory, fetchImpl: async (url, options) => {
    calls.push({ url, options });
    if (url.endsWith('/models')) return new Response(JSON.stringify({ data: available ? [row(FREELLM_MODELS[0], context), { ...row(FREELLM_MODELS[1]), pricing: { prompt: '1', completion: '0' } }, row('paid/model')] : [] }), { status });
    return new Response('data: {"choices":[{"index":0,"delta":{"content":"OK"},"finish_reason":"stop"}]}\n\ndata: [DONE]\n\n', { status: 200 });
  } });
  const discovered = await service.discover(draft);
  assert.deepEqual(discovered.models.map(m => m.id), [FREELLM_MODELS[0]]);
  assert.equal(discovered.models[0].contextMax, 1000);
  assert.equal(discovered.models[0].maxOutput, 120);
  assert.equal(calls[0].url, `${FREELLM_URL}/models`);
  assert.equal(calls[0].options.headers.authorization, undefined);
  const connection = service.save({ ...draft, models: [{ ...discovered.models[0], name: 'My model', vision: true }] }).connections[0];
  assert.equal(connection.apiKeySet, false);
  context = 2048;
  const frames = [];
  await service.stream({ selection: { connectionId: connection.id, modelId: FREELLM_MODELS[0] }, message: 'test', thinking: 'high', onFrame: f => frames.push(f) });
  assert.equal(calls.at(-1).url, `${FREELLM_URL}/chat/completions`);
  assert.equal(calls.at(-1).options.headers.authorization, undefined);
  assert.deepEqual(JSON.parse(calls.at(-1).options.body).reasoning, { effort: 'high' });
  assert.equal(frames.at(-1).type, 'done');
  assert.equal(service.list().connections[0].models[0].contextMax, 2048);
  assert.equal(service.list().connections[0].models[0].vision, true, 'keep the explicitly selected picture setting');
  assert.equal(service.list().connections[0].models[0].name, 'My model');
  await service.stream({ selection: { connectionId: connection.id, modelId: FREELLM_MODELS[0] }, message: 'test', thinking: 'max', onFrame() {} });
  assert.deepEqual(JSON.parse(calls.at(-1).options.body).reasoning, { effort: 'high' });
  available = false;
  const before = calls.length;
  await assert.rejects(service.stream({ selection: { connectionId: connection.id, modelId: FREELLM_MODELS[0] }, message: 'test', onFrame() {} }), /unavailable/);
  assert.equal(calls.length, before + 1, 'no completion sent for a missing model');
  status = 429;
  await assert.rejects(service.refresh({ connectionId: connection.id, modelId: FREELLM_MODELS[0] }), /rate limited/);
  assert.throws(() => service.save({ ...draft, models: [{ id: 'paid/model' }] }), /supported free/);
  assert.throws(() => service.save({ ...draft, apiKey: 'personal-key', models: [{ id: FREELLM_MODELS[0] }] }), /without an API key/);
  assert.throws(() => service.save({ ...draft, baseUrl: 'https://other.example/v1', models: [{ id: FREELLM_MODELS[0] }] }), /official anonymous gateway/);
});

test('agent route removes its placeholder authorization and forwards only allowed free models', async t => {
  const seen = [];
  const upstream = http.createServer((req, res) => { const chunks = []; req.on('data', c => chunks.push(c)); req.on('end', () => { seen.push({ headers: req.headers, body: JSON.parse(Buffer.concat(chunks)) }); res.writeHead(200, { 'content-type': 'application/json' }); res.end('{}'); }); });
  const upstreamBase = await listen(upstream);
  const proxy = http.createServer((req, res) => createLlmProxy({ targetOf: () => ({ base: `${upstreamBase}/v1`, anonymousFree: true, allowedModels: [FREELLM_MODELS[0]], allowedPermits: [{ id: 'turn-1', model: FREELLM_MODELS[0] }] }), samplingNow: () => ({ temperature: 0.1 }) })(req, res, 'route', '/v1/chat/completions'));
  const proxyBase = await listen(proxy);
  t.after(async () => { await close(proxy); await close(upstream); });
  const profile = buildProfile({ connections: [{ id: 'free', provider: 'freellm', name: 'FreeLLM', baseUrl: FREELLM_URL, protocol: 'openai-chat', apiKey: '', models: [{ id: FREELLM_MODELS[0], contextMax: 1000, maxOutput: 120 }] }], proxyBase, proxyNonce: 'testnonce' });
  const route = profile.routes.find(r => r.connectionId === 'free');
  assert.ok(route);
  assert.deepEqual(profile.shapeTargets[`${route.route}~free-testnonce`], { base: FREELLM_URL, anonymousFree: true, ownerRoute: route.route });
  const body = { model: FREELLM_MODELS[0], messages: [{ role: 'user', content: 'test' }] };
  const res = await fetch(proxyBase, { method: 'POST', headers: { authorization: 'Bearer not-needed', cookie: 'local-secret', 'content-type': 'application/json' }, body: JSON.stringify(body) });
  assert.equal(res.status, 200);
  assert.equal(seen[0].headers.authorization, undefined);
  assert.equal(seen[0].headers.cookie, undefined);
  assert.deepEqual(seen[0].body, body, 'cloud requests are not shaped by local sampling');
  const denied = await fetch(proxyBase, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ ...body, model: 'paid/model' }) });
  assert.equal(denied.status, 400);
  assert.equal(seen.length, 1);
});

test('a Harness agent turn reaches an anonymous model without the placeholder token', { skip: !resolveHarness({ env: process.env }).ok }, async t => {
  const worker = await startScriptedWorker({ model: FREELLM_MODELS[0] });
  const dir = mkdtempSync(join(tmpdir(), 'strata-free-agent-'));
  const workspace = join(dir, 'workspace'); mkdirSync(workspace);
  let bridge;
  const proxy = createLlmProxy({ targetOf: key => { const target = bridge.llmTarget(key); return target?.anonymousFree ? { ...target, base: worker.url } : target; }, samplingNow: () => null });
  const front = http.createServer((req, res) => { const match = /^\/api\/internal\/agent-llm\/([^/]+)(\/.*)$/.exec(req.url); if (!match) { res.writeHead(404); return res.end(); } proxy(req, res, match[1], match[2]); });
  const local = await listen(front);
  const connection = { id: 'free', provider: 'freellm', name: 'FreeLLM', baseUrl: FREELLM_URL, protocol: 'openai-chat', apiKey: '', models: [{ id: FREELLM_MODELS[0], contextMax: 32768, maxOutput: 4096, vision: false, reasoning: true }] };
  bridge = createAgentBridge({ dataDir: dir, localInstances: () => [], connections: () => [connection], env: process.env, startTimeoutMs: 90_000, proxyBase: `${local}/api/internal/agent-llm` });
  t.after(async () => { await bridge.close(); await worker.close(); await close(front); try { rmSync(dir, { recursive: true, force: true, maxRetries: 3 }); } catch { /* Harness may retain temporary ACLs */ } });
  const frames = [];
  await bridge.runTurn({ chatId: 'free-agent', choice: { connectionId: 'free', modelId: FREELLM_MODELS[0] }, message: 'SCRIPT:echo hello', workspacePath: workspace, mode: 'bypass', thinking: 'High', onFrame: f => frames.push(f) });
  assert.equal(worker.requests.at(-1)?.authorization, 'absent');
  assert.equal(worker.requests.at(-1)?.model, FREELLM_MODELS[0]);
  assert.equal(worker.requests.at(-1)?.params.reasoning?.effort, 'high');
  assert.ok(frames.some(f => f.type === 'delta' && f.text.includes('hello')));
});
